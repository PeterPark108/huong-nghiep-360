for i in range(5): x.post(B + "/dang-nhap", data=dict(_csrf=tok(x, B + "/dang-nhap"), username="chuweb", password="sai" + str(i)))
r = x.post(B + "/dang-nhap", data=dict(_csrf=tok(x, B + "/dang-nhap"), username="chuweb", password=PW))
